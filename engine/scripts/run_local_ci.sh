#!/usr/bin/env bash
# CPU-only provisional evidence. Run from a clean, committed Linux checkout.
set -Eeuo pipefail
profile=${1:?Usage: bash engine/scripts/run_local_ci.sh quick|regression|matrix|database EVIDENCE_DIR}
case "$profile" in quick|regression|matrix|database) ;; *) exit 2 ;; esac
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$repo"
test -z "$(git status --porcelain)" || { echo 'Commit or isolate source changes first.'; exit 2; }
evidence=$(realpath -m "${2:?Supply a new evidence directory outside the checkout}")
case "$evidence/" in "$repo/"*) echo 'Evidence must be outside the checkout.'; exit 2 ;; esac
mkdir "$evidence" # Never overwrite an earlier run.
export TZ=UTC
jobs=${HCP_LOCAL_BUILD_JOBS:-2}
[[ "$jobs" =~ ^[1-9][0-9]*$ ]] || exit 2
build="$repo/engine/build"
mkdir -p "$build"
exec 9>"$build/.local-ci.lock"
flock -n 9 || { echo 'Another local CI profile owns this build.'; exit 2; }
step=preflight
ctest_started=0
finish() {
  local result=$?
  trap - EXIT
  set +e
  git status --porcelain > "$evidence/source-after.txt"
  git rev-parse HEAD > "$evidence/head-after.txt"
  if ! cmp -s "$evidence/head.txt" "$evidence/head-after.txt" ||
     test -s "$evidence/source-after.txt"; then
    result=1
    step=source-changed-during-run
  fi
  if test "$ctest_started" = 1 && test -f "$build/Testing/Temporary/LastTest.log"; then
    cp "$build/Testing/Temporary/LastTest.log" "$evidence/LastTest.log"
  fi
  printf 'profile=%s\nexit_code=%s\nlast_step=%s\nfinished_utc=%s\nscope=local CPU provisional evidence; not hosted parity or acceptance\n' \
    "$profile" "$result" "$step" "$(date -u +%FT%TZ)" > "$evidence/result.txt"
  # SHA256SUMS is explicitly excluded from its own input list.
  # shellcheck disable=SC2094
  (cd "$evidence" && find . -type f ! -name SHA256SUMS -print0 |
    sort -z | xargs -0 sha256sum > SHA256SUMS)
  printf 'Local CI exit=%s; evidence=%s\n' "$result" "$evidence"
  exit "$result"
}
git rev-parse HEAD > "$evidence/head.txt"
trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
run() {
  step=$1; shift
  {
    printf '%s\t' "$step"
    printf '%q ' "$@"
    printf '\n'
  } >> "$evidence/commands.txt"
  printf '[%s] %s\n' "$(date -u +%FT%TZ)" "$step"
  "$@" > "$evidence/$step.log" 2>&1
}
{
  date -u +%FT%TZ
  uname -srmo
  cat /etc/os-release
  lscpu
  free -h
  uptime
  printf 'profile=%s build_jobs=%s test_jobs=1 shared_host=yes\n' "$profile" "$jobs"
  cmake --version
  /usr/lib/llvm-15/bin/clang++ --version
  /usr/lib/llvm-15/bin/llvm-config --version
} > "$evidence/environment.txt"
git rev-parse HEAD:engine/taichi > "$evidence/taichi-tree.txt"
git submodule status --recursive > "$evidence/submodules.txt"
if grep -Eq '^[-+U]' "$evidence/submodules.txt"; then
  echo 'Initialize exact pinned submodules before running.'; exit 2
fi
# Reuse incremental build products, but always reconfigure and rebuild the
# recorded source. Disable all GPU backends explicitly, including qualification.
run configure-taichi cmake -S engine/taichi -B engine/taichi/build-review -G Ninja \
  -DCMAKE_BUILD_TYPE=Release -DCMAKE_C_COMPILER=/usr/lib/llvm-15/bin/clang \
  -DCMAKE_CXX_COMPILER=/usr/lib/llvm-15/bin/clang++ \
  -DLLVM_DIR=/usr/lib/llvm-15/lib/cmake/llvm -DCLANG_EXECUTABLE=/usr/lib/llvm-15/bin/clang \
  -DTI_WITH_PYTHON=OFF -DTI_WITH_C_API=ON -DTI_WITH_CUDA=OFF -DTI_WITH_AMDGPU=OFF \
  -DTI_WITH_OPENGL=OFF -DTI_WITH_VULKAN=OFF -DTI_WITH_METAL=OFF \
  -DTI_WITH_DX11=OFF -DTI_WITH_DX12=OFF -DTI_WITH_GGUI=OFF -DTI_WITH_BACKTRACE=OFF \
  -DTI_BUILD_TESTS=OFF -DTI_BUILD_EXAMPLES=OFF -DTI_BUILD_RHI_EXAMPLES=OFF
run build-taichi cmake --build engine/taichi/build-review --target taichi_c_api -j "$jobs"
run configure-engine cmake -S engine -B "$build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DENGINE_TAICHI_ROOT="$repo/engine/taichi" \
  -DENGINE_TAICHI_BUILD="$repo/engine/taichi/build-review" \
  -DENGINE_TAICHI_RUNTIME_SOURCE="$repo/engine/taichi/taichi/runtime/llvm/runtime_module" \
  -DCMAKE_CXX_COMPILER=/usr/lib/llvm-15/bin/clang++ \
  -DENGINE_LLVM_CONFIG=/usr/lib/llvm-15/bin/llvm-config -DENGINE_TAICHI_CUDA=OFF \
  -DHCP_WITH_CUDA_QUALIFICATION=OFF -DHCP_WITH_WARM_INTEGRATION=ON -DHCP_WITH_VIEWPORT=ON
run build-engine cmake --build "$build" -j "$jobs"
cmake -LA -N "$build" > "$evidence/engine-cmake.txt"
cmake -LA -N engine/taichi/build-review > "$evidence/taichi-cmake.txt"
# Generated by the configure step above.
# shellcheck source=/dev/null
source "$build/engine-env.sh"
run backend "$build/engine_devices" --cpu-only
find "$build" -maxdepth 1 -type f -executable -print0 |
  sort -z | xargs -0 sha256sum > "$evidence/binaries.sha256"
sha256sum "$build/taichi-runtime/runtime_x64.bc" >> "$evidence/binaries.sha256"
case "$profile" in
  quick)
    ctest_started=1
    run tests ctest --test-dir "$build" -j 1 --no-tests=error --output-on-failure \
      -R '^(engine_smoke_test|prepared_capacity_test|strict_math_cpu)$' \
      --output-log "$evidence/ctest.log"
    run placement-math "$build/placement_math_test" --threads 1
    run placement-capacity "$build/live_hierarchy_test" --threads 1 --case placement_capacity
    ;;
  regression)
    ctest_started=1
    run tests ctest --test-dir "$build" -j 1 --no-tests=error --output-on-failure \
      --output-log "$evidence/ctest.log"
    ;;
  matrix)
    for workers in 1 2; do
      for mode in bulk direct; do
        for compiler in default no-unroll; do
          args=(--threads "$workers")
          test "$mode" != direct || args+=(--direct)
          test "$compiler" != no-unroll || args+=(--compiler-no-unroll)
          label="$workers-$mode-$compiler"
          ir="$evidence/$label"
          mkdir -p "$ir/selection" "$ir/contact-ticks" "$ir/placement"
          run "$label-ir" env HCP_C3_IR_DIR="$ir" "$build/live_hierarchy_test" "${args[@]}" --case ir
          run "$label-audit" "$build/live_hierarchy_test" "${args[@]}" --audit-ir "$ir"
          run "$label-selection-ir" env HCP_B1_IR_DIR="$ir/selection" "$build/live_hierarchy_test" "${args[@]}" --case selection_ir
          run "$label-contact-ir" env HCP_B1_TICK_IR_DIR="$ir/contact-ticks" "$build/live_hierarchy_test" "${args[@]}" --case contact_tick_ir
          run "$label-placement-ir" env HCP_B2_IR_DIR="$ir/placement" "$build/live_hierarchy_test" "${args[@]}" --case placement_compiler
          if test "$compiler" = no-unroll; then
            run "$label-native" "$build/live_hierarchy_test" "${args[@]}"
            for scenario in refresh selection contact_tick placement; do
              run "$label-$scenario" "$build/live_hierarchy_test" "${args[@]}" --case "$scenario"
            done
          fi
        done
      done
      run "$workers-math-no-unroll" "$build/placement_math_test" --threads "$workers" --compiler-no-unroll
    done
    ;;
  database)
    run database bash engine/scripts/run_local_pg_acceptance.sh "$build" "$evidence/database"
    ;;
esac
step=complete
